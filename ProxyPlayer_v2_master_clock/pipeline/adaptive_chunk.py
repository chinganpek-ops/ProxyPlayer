"""
adaptive_chunk.py – адаптивный размер чанка для ProxyPlayer v1.
Возвращает размер чанка и шаг для JKL-перемотки в зависимости от скорости.

ПРИМЕЧАНИЕ (продакшен-ревью, изменений логики НЕТ):
Класс не менялся ни в одной строке. Обращаю внимание на состояние
подключения его методов к остальному пайплайну — это не баг, а
архитектурный факт, который стоит явно зафиксировать:

- get_fast_forward_stride() РЕАЛЬНО используется:
  StreamScheduler._next_fast_forward() вызывает его для шага между
  загружаемыми чанками при JKL-перемотке.
- get_chunk_size() и get_lookahead_chunks() НЕ вызываются нигде в
  присланном наборе файлов. ReaderStage в chunk_pipeline.py всегда
  читает чанк фиксированного размера FRAMES_PER_CHUNK (12 кадров),
  независимо от скорости перемотки — то есть заявленная в докстринге
  идея "при ускоренной перемотке размер чанка растёт до 24/48 кадров"
  сейчас не реализована, реализован только пропуск чанков (stride).
  Также в ReaderStage.__init__ передаётся собственный экземпляр
  AdaptiveChunkStrategy (self._adaptive), который сохраняется, но
  никогда не читается.

Я не стал ни удалять эти два метода, ни доделывать их подключение —
это меняло бы поведение продукта (реальный размер читаемого блока при
быстрой перемотке), а не чинило баг. Если хотите, чтобы чтение при
JKL x4/x8 реально забирало более крупные чанки (меньше операций I/O при
перемотке) — это отдельная, осознанная доработка ReaderStage, а не
"уборка": скажите, и я сделаю её отдельным шагом с понятным описанием
эффекта.
"""

from config.timebase import FRAMES_PER_CHUNK


class AdaptiveChunkStrategy:
    """
    Определяет размер чанка и шаг для JKL-перемотки на основе текущей скорости.
    
    При нормальной скорости используется базовый размер чанка (12 кадров).
    При ускоренной перемотке размер увеличивается для снижения количества чтений,
    а шаг между загружаемыми чанками растёт пропорционально скорости.
    """

    def __init__(self, base_frames_per_chunk: int = FRAMES_PER_CHUNK):
        self.base_frames_per_chunk = base_frames_per_chunk

    def get_chunk_size(self, speed: float) -> int:
        """
        Возвращает количество кадров в чанке для заданной скорости.
        
        speed = 1.0 → 12 кадров (стандарт)
        speed ≤ 4.0 → 24 кадра
        speed > 4.0 → 48 кадров
        """
        if speed <= 1.0:
            return self.base_frames_per_chunk
        elif speed <= 4.0:
            return self.base_frames_per_chunk * 2
        else:
            return self.base_frames_per_chunk * 4

    def get_fast_forward_stride(self, speed: float) -> int:
        """
        Возвращает шаг между загружаемыми чанками для JKL-перемотки.
        
        speed = 1.0 → 1 (каждый чанк)
        speed = 2.0 → 2 (каждый второй)
        speed = 4.0 → 4 (каждый четвёртый)
        speed = 8.0 → 8 (каждый восьмой)
        """
        return max(1, int(speed))

    def get_lookahead_chunks(self, speed: float, buffer_size_frames: int) -> int:
        """
        Возвращает количество чанков для предварительной загрузки.
        
        При нормальной скорости: буфер заполняется на 30% вперёд.
        При ускоренной: загружается по 2 чанка (быстрый темп).
        """
        if speed <= 1.0:
            # 30% буфера в чанках
            return max(1, int(buffer_size_frames * 0.3 / self.base_frames_per_chunk))
        else:
            return 2
